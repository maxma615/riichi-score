import { readFileSync, writeFileSync } from "node:fs";
for (const [name, exports] of [
  [
    "scoring",
    ["ValidationError", "FU", "integer", "points", "defaults", "settle"],
  ],
  ["fu", ["calculateFu"]],
  ["yaku", ["YAKU", "searchYaku", "mahjongTerm"]],
  ["lookup", ["lookup"]],
  ["settlement-view", ["roundStatus", "settlementView"]],
]) {
  const source = readFileSync(
    new URL(`../src/${name}.js`, import.meta.url),
    "utf8",
  )
    .replace(/export /g, "")
    .replace(
      'import { FU, points } from "./scoring.js";',
      "const { FU, points } = require('./scoring');",
    )
    .replace(
      'import { points, settle } from "./scoring.js";',
      "const { points, settle } = require('./scoring');",
    )
    .replace("structuredClone(state)", "JSON.parse(JSON.stringify(state))");
  writeFileSync(
    new URL(`../miniprogram/utils/${name}.js`, import.meta.url),
    "// Generated by scripts/sync-mini-core.mjs; edit src instead.\n" +
      source +
      "\nmodule.exports = { " +
      exports.join(", ") +
      " };\n",
  );
}

// The native client uses the exact same timing and score interpolation as the web table.
const { build } = await import("esbuild");
await build({
  entryPoints: ["src/online/client/settlement-presentation.ts"],
  bundle: true,
  platform: "neutral",
  format: "cjs",
  target: "es2018",
  outfile: "miniprogram/utils/online-timing.js",
  banner: {
    js: "// Generated by scripts/sync-mini-core.mjs; edit src/online/client/settlement-presentation.ts instead.",
  },
});

const { fileURLToPath } = await import("node:url");
await build({
  stdin: {
    contents:
      "export * from '../domain/round-opening'; export * from './hand-rack';",
    resolveDir: fileURLToPath(new URL("../src/online/client", import.meta.url)),
    sourcefile: "native-opening.ts",
  },
  bundle: true,
  platform: "neutral",
  format: "cjs",
  target: "es2018",
  outfile: "miniprogram/utils/online-opening.js",
  banner: {
    js: "// Generated by scripts/sync-mini-core.mjs; edit the web round-opening / hand-rack source instead.",
  },
});

// ES2018 device engines need indexed lookup instead of ES2022 Array.at.
const openingOutput = new URL(
  "../miniprogram/utils/online-opening.js",
  import.meta.url,
);
writeFileSync(
  openingOutput,
  readFileSync(openingOutput, "utf8").replaceAll(
    "game.hand.at(-1)",
    "game.hand[game.hand.length - 1]",
  ),
);

// Generate the native layout directly from the existing web parser, without React.
const meldSource = readFileSync(new URL("../src/online/client/mahjong-meld.tsx", import.meta.url), "utf8");
const parserStart = meldSource.indexOf("type MeldSource =");
const parserEnd = meldSource.indexOf("function kindName(", parserStart);
if (parserStart < 0 || parserEnd < 0) throw Error("Web meld parser boundaries changed; update native generation.");
const nativeMeldParser = 'import Majiang from "@kobalab/majiang-core";\n' +
  meldSource.slice(parserStart, parserEnd).replace("function parseMeld(", "export function parseMeld(");

// Public event acceptance is shared with web flights; no concealed opponent faces enter it.
await build({
  stdin: {
    contents:
      nativeMeldParser + "\nexport {DiscardMotionTracker, createDiscardEventId} from './discard-motion'; export {acceptedNukiEvent} from './nuki-motion'; export {acceptedPublicCallEvent, acceptedPendingKakanEvent} from './public-call-motion';",
    resolveDir: fileURLToPath(new URL("../src/online/client", import.meta.url)),
    sourcefile: "native-motion.ts",
    loader: "ts",
  },
  bundle: true,
  platform: "neutral",
  format: "cjs",
  target: "es2018",
  outfile: "miniprogram/utils/online-motion.js",
  banner: {
    js: "// Generated by scripts/sync-mini-core.mjs; edit the web discard-motion / nuki-motion source instead.",
  },
});
const motionOutput = new URL(
  "../miniprogram/utils/online-motion.js",
  import.meta.url,
);
writeFileSync(
  motionOutput,
  readFileSync(motionOutput, "utf8").replaceAll(
    "game.hand.at(-1)",
    "game.hand[game.hand.length - 1]",
  ),
);
