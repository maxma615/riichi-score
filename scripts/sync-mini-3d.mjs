import { RoundedBoxGeometry } from "three/addons/geometries/RoundedBoxGeometry.js";
import { PlaneGeometry } from "three";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { build } from "esbuild";
const serialize = (g) => {
  const plain = g.index ? g.toNonIndexed() : g;
  return Object.fromEntries(
    ["position", "normal", "uv"].map((k) => [
      k,
      Array.from(plain.getAttribute(k).array).map(
        (x) => Math.round(x * 1e6) / 1e6,
      ),
    ]),
  );
};
const body = new RoundedBoxGeometry(0.95, 1.35, 0.6, 2, 0.065);
const back = new RoundedBoxGeometry(0.95 * 0.98, 1.35 * 0.98, 0.13, 2, 0.045);
back.translate(0, 0, -0.3 + 0.065);
const face = new PlaneGeometry(0.95 * 0.88, 1.35 * 0.91);
face.translate(0, 0, 0.303);
writeFileSync(
  "src/online/client/native-tile-geometry.json",
  JSON.stringify({
    body: serialize(body),
    back: serialize(back),
    face: serialize(face),
  }) + "\n",
);
// Tencent r108 scopes document/window but originally copies event methods onto
// Object.prototype. Give all three shim targets their own methods instead.
const vendor = readFileSync(
  "node_modules/threejs-miniprogram/dist/index.js",
  "utf8",
);
const pattern = /([A-Za-z_$][\w$]*)\.constructor\.prototype,u\.prototype/g;
if ([...vendor.matchAll(pattern)].length !== 3)
  throw Error("Pinned Tencent adapter patch no longer matches");
mkdirSync("src/online/client/vendor", { recursive: true });
writeFileSync(
  "src/online/client/vendor/native-three.cjs",
  "// Generated from threejs-miniprogram 0.0.8 (MIT); events are instance-scoped. See scripts/sync-mini-3d.mjs.\n" +
    vendor.replace(pattern, "$1,u.prototype") +
    "\n",
);
await build({
  entryPoints: ["src/online/client/native-table3d.js"],
  bundle: true,
  platform: "neutral",
  mainFields: ["main", "module"],
  format: "cjs",
  target: "es2018",
  minify: true,
  outfile: "miniprogram/utils/online-table3d.js",
  banner: {
    js: "// Generated by scripts/sync-mini-3d.mjs. Tencent threejs-miniprogram (MIT) + shared geometric table.",
  },
});
// Shader template literals may contain whitespace-only GLSL lines. Normalize
// trailing spaces in the generated distributable for clean repository diffs.
const output='miniprogram/utils/online-table3d.js';
writeFileSync(output,readFileSync(output,'utf8').replace(/[ \t]+$/gm,''));
// Preserve licenses alongside the distributable, not just in node_modules.
const { copyFileSync } = await import("node:fs");
mkdirSync("miniprogram/assets/licenses", { recursive: true });
copyFileSync(
  "node_modules/threejs-miniprogram/LICENSE",
  "miniprogram/assets/licenses/threejs-miniprogram-MIT.txt",
);
copyFileSync(
  "node_modules/three/LICENSE",
  "miniprogram/assets/licenses/Three-js-MIT.txt",
);
